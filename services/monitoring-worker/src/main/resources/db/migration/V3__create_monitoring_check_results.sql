
CREATE TABLE monitoring_worker.monitoring_check_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    job_id BIGINT NOT NULL,
    monitor_id BIGINT NOT NULL CHECK (monitor_id > 0),
    attempt_count INTEGER NOT NULL CHECK (attempt_count > 0),

    outcome VARCHAR(20) NOT NULL
        CHECK (outcome IN (
            'SUCCESS',
            'HTTP_ERROR',
            'TIMEOUT',
            'NETWORK_ERROR',
            'REJECTED'
        )),

    http_status INTEGER
        CHECK (http_status BETWEEN 100 AND 599),

    response_time_ms BIGINT NOT NULL
        CHECK (response_time_ms >= 0),

    error_code VARCHAR(100),

    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_check_results_job
        FOREIGN KEY (job_id)
        REFERENCES monitoring_worker.monitoring_jobs(id),

    CONSTRAINT ux_check_results_job_attempt
        UNIQUE (job_id, attempt_count)
);

CREATE INDEX idx_check_results_monitor_checked_at
    ON monitoring_worker.monitoring_check_results
        (monitor_id, checked_at DESC, id DESC);
