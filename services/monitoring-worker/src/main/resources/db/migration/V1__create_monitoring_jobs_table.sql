CREATE TABLE monitoring_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    monitor_id BIGINT NOT NULL
        CHECK (monitor_id > 0),

    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'CLAIMED', 'SUCCEEDED', 'FAILED')),

    due_at TIMESTAMPTZ NOT NULL,

    claimed_by VARCHAR(200),

    lease_until TIMESTAMPTZ,

    attempt_count INTEGER NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),

    last_error_code VARCHAR(100),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_monitoring_jobs_lease_consistency
        CHECK (
            (
                status = 'CLAIMED'
                AND claimed_by IS NOT NULL
                AND LENGTH(BTRIM(claimed_by)) > 0
                AND lease_until IS NOT NULL
            )
            OR
            (
                status <> 'CLAIMED'
                AND claimed_by IS NULL
                AND lease_until IS NULL
            )
        )
);

CREATE INDEX idx_monitoring_jobs_pending_due
    ON monitoring_jobs (due_at, id)
    WHERE status = 'PENDING';

CREATE INDEX idx_monitoring_jobs_expired_lease
    ON monitoring_jobs (lease_until, id)
    WHERE status = 'CLAIMED';

CREATE UNIQUE INDEX ux_monitoring_jobs_one_active_per_monitor
    ON monitoring_jobs (monitor_id)
    WHERE status IN ('PENDING', 'CLAIMED');